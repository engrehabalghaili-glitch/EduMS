"""
سكربت تشغيل واجهة المستخدم
=============================
هذا السكربت يستخدم لتشغيل واجهة Streamlit العربية للنظام.

المتطلبات:
- وجود ملفات النماذج في مجلد models/
- المكتبات المطلوبة في requirements.txt

الاستخدام:
    python scripts/run_gui.py
"""

import sys  # استيراد مكتبة sys للتعامل مع مسارات النظام
import os  # استيراد مكتبة os للتعامل مع نظام الملفات
import subprocess  # استيراد مكتبة subprocess لتشغيل أوامر خارجية

def main():  # تعريف الدالة الرئيسية
    """الدالة الرئيسية لتشغيل الواجهة"""  # وصف الدالة
    print("=" * 60)  # طباعة خط فاصل
    print("بدء تشغيل واجهة المستخدم العربية")  # طباعة رسالة البدء
    print("=" * 60)  # طباعة خط فاصل
    
    # مسار ملف الواجهة
    gui_path = 'ui/gui_app.py'  # تحديد مسار ملف الواجهة
    
    # التحقق من وجود ملف الواجهة
    if not os.path.exists(gui_path):  # التحقق من وجود الملف
        print(f"خطأ: ملف الواجهة غير موجود: {gui_path}")  # طباعة رسالة خطأ
        print("يرجى التأكد من وجود ملف الواجهة في المسار الصحيح")  # طباعة رسالة توجيه
        return  # إنهاء الدالة
    
    # تشغيل الواجهة باستخدام Streamlit
    try:  # محاولة تنفيذ الكود
        print("\nجاري تشغيل الواجهة...")  # طباعة رسالة التحميل
        print("الواجهة ستكون متاحة على: http://localhost:8501")  # طباعة رابط الواجهة
        print("اضغط Ctrl+C لإيقاف الواجهة")  # طباعة تعليمات الإيقاف
        print("=" * 60 + "\n")  # طباعة خط فاصل
        
        subprocess.run([  # تشغيل أمر خارجي
            sys.executable, '-m', 'streamlit', 'run', gui_path,  # تشغيل Streamlit على ملف الواجهة
            '--server.port', '8501',  # تحديد المنفذ
            '--server.address', 'localhost',  # تحديد العنوان
            '--browser.gatherUsageStats', 'false'  # تعطيل جمع الإحصائيات
        ])
    except KeyboardInterrupt:  # التقاط إشارة التوقف
        print("\n" + "=" * 60)  # طباعة خط فاصل
        print("تم إيقاف الواجهة")  # طباعة رسالة الإيقاف
        print("=" * 60)  # طباعة خط فاصل
    except Exception as e:  # التقاط أي خطأ
        print(f"\nخطأ أثناء تشغيل الواجهة: {e}")  # طباعة رسالة الخطأ

if __name__ == "__main__":  # التحقق من تشغيل السكربت مباشرة
    main()  # استدعاء الدالة الرئيسية
